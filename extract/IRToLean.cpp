//===-- Export a function from LLVM IR to Lean ----------------------------===//
//
// Writes a Lean file that defines one function of an IR module as a
// `LibcMath.IR.Func`, in the `llvm_func` notation. A `switch` is first lowered
// to conditional branches by LLVM's `lower-switch` pass.
//
//===----------------------------------------------------------------------===//

#include "CoreOps.h"
#include "DslEmitter.h"
#include "FunctionTranslator.h"

#include "llvm/IR/LLVMContext.h"
#include "llvm/IR/Module.h"
#include "llvm/IRReader/IRReader.h"
#include "llvm/Passes/PassBuilder.h"
#include "llvm/Support/CommandLine.h"
#include "llvm/Support/SourceMgr.h"
#include "llvm/Support/raw_ostream.h"
#include "llvm/Transforms/Utils/LowerSwitch.h"

using namespace llvm;

static cl::opt<std::string> InputFile(cl::Positional, cl::desc("<IR file>"),
                                      cl::Required);
static cl::opt<std::string>
    FunctionName("function", cl::Required,
                 cl::desc("Function to export, by its name relative to the "
                          "libc namespace, e.g. math::double_eval::expf, or "
                          "by its mangled name"));
static cl::opt<std::string> LeanName("name", cl::Required,
                                     cl::desc("Name of the Lean definition"));
static cl::opt<std::string>
    Origin("origin", cl::desc("Description of the source, for the header"));

/// Replace every `switch` of the function by comparisons and conditional
/// branches, using LLVM's own lowering. The exported fragment has no `switch`.
static void lowerSwitches(Function &F) {
  PassBuilder PB;
  LoopAnalysisManager LAM;
  FunctionAnalysisManager FAM;
  CGSCCAnalysisManager CGAM;
  ModuleAnalysisManager MAM;
  PB.registerModuleAnalyses(MAM);
  PB.registerCGSCCAnalyses(CGAM);
  PB.registerFunctionAnalyses(FAM);
  PB.registerLoopAnalyses(LAM);
  PB.crossRegisterProxies(LAM, FAM, CGAM, MAM);
  LowerSwitchPass().run(F, FAM);
}

int main(int argc, char **argv) {
  cl::ParseCommandLineOptions(argc, argv, "Export an IR function to Lean\n");

  LLVMContext Context;
  SMDiagnostic Err;
  std::unique_ptr<Module> M = parseIRFile(InputFile, Err, Context);
  if (!M) {
    Err.print(argv[0], errs());
    return 1;
  }

  SmallVector<Function *, 1> Matches;
  for (Function &F : *M)
    if (!F.isDeclaration() && (F.getName() == FunctionName ||
                               extract::relativeName(F) == FunctionName))
      Matches.push_back(&F);
  if (Matches.empty()) {
    errs() << "ir2lean: no function named " << FunctionName << "\n";
    return 1;
  }
  if (Matches.size() > 1) {
    errs() << "ir2lean: several functions are named " << FunctionName
           << "; choose one by its mangled name:\n";
    for (const Function *F : Matches)
      errs() << "  " << F->getName() << "\n";
    return 1;
  }
  Function &F = *Matches.front();
  lowerSwitches(F);

  // Translation stops the tool on unsupported input, so buffer the output to
  // avoid leaving a partial file behind.
  std::string Body;
  raw_string_ostream BodyOS(Body);
  extract::DslEmitter Emitter(BodyOS);
  extract::translateFunction(F, LeanName, Emitter);

  outs() << "import LibcMath.IR.DSL\n\n"
         << "/-! Generated by `ir2lean` from `" << F.getName() << "`"
         << (Origin.empty() ? "" : "\n(" + Origin + ")")
         << ". Do not edit. -/\n\n"
         << "namespace LibcMath.Extracted\n\n"
         << Body << "\nend LibcMath.Extracted\n";
  return 0;
}
